import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import test from "node:test";
import Extension from "../dist/index.mjs";
import { ConnectRequestPacket } from "terraria-packet";

test("the bundled extension selects the backend on every join and switch", () => {
  const original = process.cwd();
  const dir = mkdtempSync(path.join(tmpdir(), "dimensions-mcl-"));
  try {
    mkdirSync(path.join(dir, "configuration"));
    mkdirSync(path.join(dir, "build"));
    writeFileSync(path.join(dir, "configuration/cl.yaml"),
      'oldVersion: 326\noldServers: {Lobby: ""}\nallAreOldServers: false\nhotReloadEnabled: false\n');
    process.chdir(path.join(dir, "build"));
    const layer = new Extension({error: message => assert.fail(message)});
    const client = {version: "Terraria329"};
    const legacy = {client, name: "lobby"};
    const native = {client, name: "new-world"};
    const outgoing = (server, data) => {
      client.server = server;
      const packet = {data, packetType: data[2]};
      return layer.postPacketHandlers.clientHandler.handlePacket(client, packet) ? null : packet.data;
    };
    const incoming = (server, data, source = 0) => {
      const packet = {data, packetType: data[2]};
      return layer.priorPacketHandlers.serverHandler.handlePacket(server, packet, source) ? null : packet.data;
    };
    const hello = ConnectRequestPacket.toBuffer({version: client.version})._0;
    for (const route of [legacy, native, legacy]) {
      const forwarded = outgoing(route, hello);
      assert.equal(ConnectRequestPacket.parse(forwarded)._0.version, route === native ? "Terraria329" : "Terraria326");
      assert.equal(client.version, "Terraria329");
    }
    const anim326 = Buffer.from("0a0029010000003f0700", "hex");
    const anim329 = Buffer.from("0c0029010000003f07000700", "hex");
    assert.deepEqual(outgoing(legacy, anim329), anim326);
    assert.deepEqual(incoming(legacy, anim326), anim329);
    assert.equal(incoming(native, anim329), anim329);
    assert.equal(incoming(legacy, anim329, 1), anim329); // generated by Dimensions

    for (const hex of ["0300a3", "0700a401060000", "0500a5ac02"]) {
      const packet = Buffer.from(hex, "hex");
      assert.equal(outgoing(legacy, packet), null);
      assert.equal(outgoing(native, packet), packet);
    }
    const ack = Buffer.from("0300a2", "hex");
    assert.equal(incoming(legacy, ack), ack);
    const projectile = Buffer.alloc(26);
    projectile.writeUInt16LE(projectile.length);
    projectile[2] = 27;
    projectile.writeInt32LE(0x12345678, 3);
    projectile.writeInt16LE(1135, 23);
    assert.equal(outgoing(legacy, projectile), projectile);
    projectile.writeInt16LE(1136, 23);
    assert.equal(outgoing(legacy, projectile), null);
    assert.equal(outgoing(native, projectile), projectile);
  } finally {
    process.chdir(original);
    rmSync(dir, {recursive: true, force: true});
  }
});
